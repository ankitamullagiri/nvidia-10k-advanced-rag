"""Gradio demo: baseline vs enhanced RAG over NVIDIA's FY2025 annual report."""

from __future__ import annotations

import hashlib
import html
import logging
import os
from pathlib import Path

import gradio as gr
import numpy as np

from rag.models import CrossEncoderReranker, GeminiLLM, MiniLMEmbedder
from rag.pipeline import RAGPipeline, RAGResult
from rag.sources import load_document
from rag.text import chunk_pages

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger("app")

MAX_QUESTION_CHARS = 300
CACHE_DIR = Path(os.environ.get("CACHE_DIR", ".cache"))

EXAMPLES = [
    "What was NVIDIA's total revenue in fiscal 2025?",
    "What are the main risk factors NVIDIA faces?",
    "How did the Data Center segment perform?",
    "Where did NVIDIA make money?",
    "Tell me about NVIDIA's ice cream division",
]


def build_pipeline() -> tuple[RAGPipeline, str]:
    pages, source_label = load_document()
    chunks = chunk_pages(pages)
    log.info("Loaded %d pages → %d chunks from %s", len(pages), len(chunks), source_label)

    embedder = MiniLMEmbedder()
    digest = hashlib.sha256("\n".join(c.text for c in chunks).encode()).hexdigest()[:16]
    cache = CACHE_DIR / f"embeddings_{digest}.npy"
    if cache.exists():
        embeddings = np.load(cache)
        log.info("Loaded cached embeddings %s", cache)
    else:
        embeddings = embedder([c.text for c in chunks])
        CACHE_DIR.mkdir(parents=True, exist_ok=True)
        np.save(cache, embeddings)

    pipeline = RAGPipeline(chunks, embedder, CrossEncoderReranker(), GeminiLLM(), embeddings=embeddings)
    return pipeline, f"{source_label} · {len(chunks)} chunks"


try:
    PIPELINE, SOURCE_INFO = build_pipeline()
    STARTUP_ERROR = None
except Exception as exc:  # show a clear message in the UI instead of a crashed Space
    log.exception("Startup failed")
    PIPELINE, SOURCE_INFO, STARTUP_ERROR = None, "", str(exc)


def render_sources(result: RAGResult) -> str:
    label = "p." if "page" in SOURCE_INFO else "§"
    parts = []
    for n, chunk in enumerate(result.sources, start=1):
        snippet = html.escape(chunk.text[:600]) + ("…" if len(chunk.text) > 600 else "")
        parts.append(f"<details><summary><b>[{n}]</b> {label}{chunk.page}</summary>\n\n{snippet}\n\n</details>")
    return "\n".join(parts) or "_No sources retrieved._"


def render(result: RAGResult) -> str:
    title = "### ✨ Enhanced RAG" if result.mode == "enhanced" else "### Baseline RAG (vector top-3, vanilla prompt)"
    out = [title]
    if result.rewritten_query:
        out.append(f"**Rewritten query:** _{result.rewritten_query}_\n")
    out.append(result.answer)
    out.append("\n**Pipeline:** " + " → ".join(result.trace))
    out.append("\n**Retrieved context**\n" + render_sources(result))
    return "\n".join(out)


def answer(question: str, mode: str):
    if STARTUP_ERROR:
        msg = f"⚠️ The app failed to start: `{STARTUP_ERROR}`"
        return msg, msg
    question = (question or "").strip()
    if not question:
        return "Type a question first.", ""
    if len(question) > MAX_QUESTION_CHARS:
        return f"Please keep questions under {MAX_QUESTION_CHARS} characters.", ""

    try:
        enhanced = render(PIPELINE.enhanced(question))
        baseline = render(PIPELINE.baseline(question)) if mode == "Compare with baseline" else ""
    except Exception as exc:
        log.exception("Query failed")
        msg = "⚠️ The language model is unavailable right now (likely a rate limit). Try again in a minute."
        if "API key" in str(exc) or "PERMISSION_DENIED" in str(exc):
            msg = "⚠️ The Gemini API key is missing or invalid."
        return msg, ""
    return enhanced, baseline


with gr.Blocks(title="NVIDIA 10-K RAG", theme=gr.themes.Soft()) as demo:
    gr.Markdown(
        "# Ask NVIDIA's FY2025 Annual Report\n"
        "Advanced RAG: **LLM query rewriting → hybrid BM25 + vector retrieval (RRF) → "
        "cross-encoder reranking → grounded answer**, side by side with a plain vector-search baseline.  \n"
        "[Code on GitHub](https://github.com/ankitamullagiri/nvidia-10k-advanced-rag)"
    )
    if SOURCE_INFO:
        gr.Markdown(f"<small>Corpus: {SOURCE_INFO}</small>")

    with gr.Row():
        question = gr.Textbox(label="Question", placeholder="e.g. How did the Data Center segment perform?", scale=4)
        mode = gr.Radio(["Compare with baseline", "Enhanced only"], value="Compare with baseline", label="Mode", scale=1)
    ask = gr.Button("Ask", variant="primary")
    gr.Examples(EXAMPLES, inputs=question)

    with gr.Row():
        enhanced_out = gr.Markdown(label="Enhanced RAG")
        baseline_out = gr.Markdown(label="Baseline RAG")
    gr.Markdown("<small>Left: enhanced pipeline · Right: baseline. Answers are generated by Gemini 2.5 Flash "
                "from the retrieved passages only; this is a portfolio demo, not investment advice.</small>")

    for trigger in (ask.click, question.submit):
        trigger(answer, inputs=[question, mode], outputs=[enhanced_out, baseline_out], concurrency_limit=2)

if __name__ == "__main__":
    demo.queue(max_size=20).launch()
